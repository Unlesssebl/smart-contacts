#!/usr/bin/env bash
set -e

# ==============================================================================
# Скрипт настройки UFW (Uncomplicated Firewall) для production-сервера
# Разрешает только: SSH (22), HTTP (80), HTTPS (443)
# Блокирует все остальные внешние входящие подключения.
# ==============================================================================

if [ "$EUID" -ne 0 ]; then
  echo "❌ Ошибка: этот скрипт должен быть запущен с правами sudo (sudo bash scripts/setup_firewall.sh)"
  exit 1
fi

echo "=================================================================="
echo "Настройка UFW фаервола"
echo "=================================================================="

# 1. Сброс к базовым политикам
echo "1. Установка политик по умолчанию..."
ufw default deny incoming
ufw default allow outgoing
ufw default allow routed

# 2. Разрешаем необходимые порты
echo "2. Добавление разрешающих правил..."
ufw allow 22/tcp comment 'SSH Management'
ufw allow 80/tcp comment 'HTTP Web'
ufw allow 443/tcp comment 'HTTPS Web'

# 3. Разрешаем трафик на интерфейсе loopback (локальные сервисы)
ufw allow in on lo

# 4. Включаем фаервол (без интерактивного подтверждения)
echo "3. Активация UFW..."
ufw --force enable

echo ""
echo "=================================================================="
echo "Текущий статус UFW:"
echo "=================================================================="
ufw status verbose
echo "=================================================================="
echo "✅ Фаервол успешно настроен и активен!"
echo "   Открыты только порты: 22 (SSH), 80 (HTTP), 443 (HTTPS)."
echo "=================================================================="
